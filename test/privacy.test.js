const P = require('../src/main/privacy');
const assert = require('assert');
assert.equal(P.siteOf('news.bbc.co.uk'), 'bbc.co.uk');
assert.equal(P.siteOf('www.amazon.in'), 'amazon.in');
assert.equal(P.siteOf('a.b.myblog.github.io'), 'myblog.github.io');
assert.equal(P.siteOf('mail.google.com'), 'google.com');
console.log('✓ site detection (co.uk, .in, github.io)');
assert.ok(P.sameParty('accounts.google.com', 'www.youtube.com'));
assert.ok(P.sameParty('login.microsoftonline.com', 'outlook.live.com'));
assert.ok(!P.sameParty('doubleclick.net', 'bbc.co.uk'));
console.log('✓ Google/YouTube and Microsoft sign-in domains treated as one party');
assert.equal(P.cleanUrl('https://shop.com/item?id=5&utm_source=fb&utm_medium=x&fbclid=abc&gclid=1'), 'https://shop.com/item?id=5');
assert.equal(P.cleanUrl('https://www.youtube.com/watch?v=abc&si=TRACK&pp=xyz'), 'https://www.youtube.com/watch?v=abc');
assert.equal(P.cleanUrl('https://example.com/search?feature=new&page=2'), 'https://example.com/search?feature=new&page=2');
assert.equal(P.cleanUrl('https://site.com/p?mc_eid=1&_hsenc=2&q=keep'), 'https://site.com/p?q=keep');
console.log('✓ tracking parameters stripped, real parameters kept');
assert.equal(P.unwrapRedirect('https://www.google.com/url?q=https://bbc.co.uk/news?utm_source=g&sa=U'), 'https://bbc.co.uk/news');
assert.equal(P.unwrapRedirect('https://l.facebook.com/l.php?u=https%3A%2F%2Fexample.com%2F%3Ffbclid%3Dx&h=1'), 'https://example.com/');
assert.equal(P.unwrapRedirect('https://www.youtube.com/redirect?q=https%3A%2F%2Fblog.com%2Fpost'), 'https://blog.com/post');
assert.equal(P.unwrapRedirect('https://example.com/url?q=x'), null);
console.log('✓ redirect trackers (Google, Facebook, YouTube) skipped straight to the real site');
const id = P.chromeIdentity('140.0.7339.80');
assert.ok(id.ua.includes('Chrome/140.0.0.0') && !/Electron|Seeker/.test(id.ua) && id.secChUa.includes('"Google Chrome";v="140"'));
console.log('✓ identity matches Google Chrome 140:', id.ua);
assert.ok(P.isException('accounts.google.com', ['google.com']) && P.isException('www.youtube.com', ['google.com']) && !P.isException('bbc.com', ['google.com']));
console.log('\nALL PRIVACY TESTS PASSED');
